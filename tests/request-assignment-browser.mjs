import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.BASE_URL ?? 'http://127.0.0.1:5173';
const proxy = process.env.HTTPS_PROXY ?? process.env.https_proxy;
const browser = await chromium.launch({ headless: true, channel: 'chromium', args: ['--no-sandbox'],
  ...(proxy && !/^http:\/\/(127\.0\.0\.1|localhost)/.test(base) ? { proxy: { server: proxy } } : {}) });
const tomorrow = new Date(Date.now() + 32 * 3600000).toISOString().slice(0, 10);
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/demo', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.waitForFunction(() => document.querySelector('[aria-label="演示角色"]')?.value === 'admin', {}, { timeout: 90000 });
  await page.getByRole('button', { name: '申请资源', exact: true }).click();
  let d = page.getByRole('dialog');
  for (const name of ['Atlas-950-01', 'Atlas-950-02', 'Atlas-950-03'])
    await d.locator('.resource-picker').getByRole('checkbox', { name: new RegExp(name) }).check();
  await d.getByLabel('开始时间 *', { exact: true }).fill(`${tomorrow}T09:00`);
  await d.getByLabel('结束时间 *', { exact: true }).fill(`${tomorrow}T19:00`);
  await d.getByLabel('任务用途').fill('QA统一预留3台');
  await d.getByRole('button', { name: '提交申请', exact: true }).click();
  await d.waitFor({ state: 'hidden' });
  const row = purpose => page.getByRole('row').filter({ hasText: purpose });
  await row('QA统一预留3台').getByRole('button', { name: '审批', exact: true }).click();
  d = page.getByRole('dialog');
  await d.getByLabel('审批说明（可选）').fill('QA统一批准');
  await d.getByRole('button', { name: '确认批准', exact: true }).click();
  await d.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '全部申请', exact: true }).click();
  await row('QA统一预留3台').getByRole('button', { name: '调整使用组与事项', exact: true }).click();
  d = page.getByRole('dialog');
  assert.equal(await d.locator('.operation-feedback').count(), 0);
  assert(await d.getByRole('button', { name: '确认调整', exact: true }).isDisabled());
  await d.getByRole('button', { name: '清空选择', exact: true }).click();
  await d.getByLabel('搜索待调整服务器').fill('192.0.2.21,192.0.2.22');
  assert.equal(await d.getByRole('checkbox').count(), 2);
  await d.getByRole('checkbox', { name: /Atlas-950-01/ }).check();
  await d.getByRole('checkbox', { name: /Atlas-950-02/ }).check();
  await d.getByLabel('调整后的使用组').selectOption('g2');
  await d.getByLabel('调整后的使用事项').fill('QA多模态训练');
  assert.match(await d.getByRole('region', { name: '本次调整的服务器' }).innerText(), /已选 2 \/ 3/);
  await page.screenshot({ path: 'outputs/assignment-desktop.png' });
  await d.getByRole('button', { name: '确认调整', exact: true }).click();
  await d.waitFor({ state: 'hidden' });
  assert.match(await row('QA统一预留3台').innerText(), /Atlas-950-03/);
  assert(!/Atlas-950-0[12]/.test(await row('QA统一预留3台').innerText()));
  assert.match(await row('QA多模态训练').innerText(), /多模态算法组/);
  assert.match(await row('QA多模态训练').innerText(), /已批准/);
  await row('QA多模态训练').getByRole('button', { name: '详情', exact: true }).click();
  d = page.getByRole('dialog');
  assert.match(await d.innerText(), /QA统一批准/);
  assert.match(await d.innerText(), /从原申请拆分调整/);
  assert.equal(await d.getByRole('region', { name: '实际有效排期' }).locator('.booking-list > div').count(), 2);
  await d.getByRole('button', { name: '调整使用组与事项', exact: true }).click();
  d = page.getByRole('dialog');
  await page.setViewportSize({ width: 390, height: 700 });
  await d.getByRole('checkbox', { name: /Atlas-950-02/ }).uncheck();
  await d.getByLabel('调整后的使用组').selectOption('g3');
  await d.getByLabel('调整后的使用事项').fill('QA推理测试');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  assert(await d.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.screenshot({ path: 'outputs/assignment-mobile.png' });
  await d.getByRole('button', { name: '确认调整', exact: true }).click();
  await d.waitFor({ state: 'hidden' });
  assert.match(await row('QA推理测试').innerText(), /推理优化组/);
  assert.match(await row('QA多模态训练').innerText(), /Atlas-950-02/);
  // Update all of this single-server child without creating another split.
  await row('QA推理测试').getByRole('button', { name: '调整使用组与事项', exact: true }).click();
  await page.getByRole('dialog').getByLabel('调整后的使用事项').fill('QA推理测试最终事项');
  await page.getByRole('dialog').getByRole('button', { name: '确认调整', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await row('QA推理测试最终事项').count(), 1);
  await page.getByRole('button', { name: '使用排期', exact: true }).click();
  await page.getByLabel('排期日期', { exact: true }).fill(tomorrow);
  await page.getByLabel('搜索排期资源').fill('192.0.2.21 192.0.2.22 192.0.2.23');
  for (const purpose of ['QA统一预留3台', 'QA多模态训练', 'QA推理测试最终事项'])
    assert.equal(await page.locator('.timeline-booking').filter({ hasText: purpose }).count(), 1);
  // Resource detail starts an adjustment with just the clicked machine selected.
  await page.locator('.timeline-booking').filter({ hasText: 'QA多模态训练' }).click();
  d = page.getByRole('dialog');
  await d.getByRole('button', { name: '调整组与事项', exact: true }).click();
  d = page.getByRole('dialog');
  assert.equal(await d.getByRole('checkbox', { checked: true }).count(), 1);
  assert.match(await d.getByRole('region', { name: '本次调整的服务器' }).innerText(), /Atlas-950-02/);
  await d.getByLabel('关闭', { exact: true }).click();
  await page.getByRole('button', { name: '变更历史', exact: true }).click();
  assert.match(await page.locator('main').innerText(), /调整使用组与事项/);
  await page.getByRole('button', { name: '申请与审批', exact: true }).click();
  await page.getByLabel('演示角色').selectOption('contact');
  assert.equal(await page.getByRole('button', { name: '调整使用组与事项', exact: true }).count(), 0);
  assert.equal(await row('QA多模态训练').getByRole('button', { name: '取消', exact: true }).count(), 0);
  await page.getByLabel('演示角色').selectOption('visitor');
  assert.equal(await page.getByRole('button', { name: '调整使用组与事项', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: unified 3-server application/approval; multi- and single-server group/task splits, repeated whole-child editing, retained approval and exact time segments, synchronized schedule/detail/history, batch search/selection/mobile layout, and admin-only controls.');
} finally { await browser.close(); }
