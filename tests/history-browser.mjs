import { chromium } from "playwright";
import assert from "node:assert/strict";
const base = process.env.BASE_URL ?? "http://127.0.0.1:5173";
const proxy = process.env.HTTPS_PROXY ?? process.env.https_proxy;
const browser = await chromium.launch({ headless: true, channel: "chromium", args: ["--no-sandbox"],
  ...(proxy && !/^http:\/\/(127\.0\.0\.1|localhost)/.test(base) ? { proxy: { server: proxy } } : {}),
});
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.clock.setFixedTime(new Date("2026-10-21T02:00:00Z"));
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(base + "/demo", { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "服务器资源", exact: true }).click();
  await page.clock.setFixedTime(new Date("2026-10-20T15:55:00Z"));
  await page.getByRole("button", { name: "添加服务器", exact: true }).click();
  let d = page.getByRole("dialog");
  await d.getByLabel("服务器名称").fill("QA-History-Search");
  await d.getByLabel("服务器类型").fill("QA历史类型");
  await d.getByLabel("IP 地址").fill("198.51.100.213");
  await d.getByRole("button", { name: "保存服务器", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  await page.clock.setFixedTime(new Date("2026-10-20T16:05:00Z"));
  await page.getByRole("button", { name: "编辑 QA-History-Search", exact: true }).click();
  d = page.getByRole("dialog");
  await d.getByLabel("位置").fill("上海测试位置");
  await d.getByRole("button", { name: "保存服务器", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "变更历史", exact: true }).click();
  const records = page.locator(".audit-item");
  assert.equal(await records.count(), 4);
  await page.getByRole("button", { name: "变更类型筛选", exact: true }).click();
  d = page.getByRole("dialog", { name: "变更类型筛选", exact: true });
  await d.getByRole("button", { name: "清空", exact: true }).click();
  await d.getByRole("checkbox", { name: "新增服务器", exact: true }).check();
  await d.getByRole("checkbox", { name: "修改服务器", exact: true }).check();
  await d.getByRole("button", { name: "确定", exact: true }).click();
  assert.equal(await records.count(), 2);
  await page.getByLabel("搜索历史", { exact: true }).fill("QA-History-Search");
  await page.getByLabel("历史开始时间", { exact: true }).fill("2026-10-20T23:50");
  await page.getByLabel("历史结束时间", { exact: true }).fill("2026-10-21T00:00");
  await page.getByRole("button", { name: "查询时间段", exact: true }).click();
  assert.equal(await records.count(), 1);
  assert((await records.first().innerText()).includes("新增服务器"));
  assert((await records.locator("time").innerText()).includes("2026/10/20 23:55:00"));
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "导出历史", exact: true }).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const csv = Buffer.concat(chunks).toString("utf8");
  assert(csv.includes("北京时间")); assert(csv.includes("2026/10/20 23:55:00"));
  assert(csv.includes("新增服务器")); assert(!csv.includes("修改服务器"));
  assert.equal(csv.split(/\r?\n/).filter(Boolean).length, 2);
  await page.getByLabel("历史开始时间").fill("2026-10-22T00:00");
  await page.getByRole("button", { name: "查询时间段", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "结束时间不能早于开始时间" }).waitFor();
  assert.equal(await records.count(), 1);
  await page.getByRole("button", { name: "重置筛选", exact: true }).click();
  assert.equal(await records.count(), 4);
  await page.getByLabel("历史开始时间").fill("2026-10-21T00:00");
  await page.getByRole("button", { name: "查询时间段", exact: true }).click();
  assert.equal(await records.count(), 3);
  await page.getByRole("button", { name: "重置筛选", exact: true }).click();
  await page.getByLabel("历史结束时间").fill("2026-10-20T23:55");
  await page.getByRole("button", { name: "查询时间段", exact: true }).click();
  assert.equal(await records.count(), 1);
  await page.getByLabel("搜索历史").fill("不存在的记录");
  await page.getByRole("heading", { name: "没有符合条件的变更记录", exact: true }).waitFor();
  assert(await page.getByRole("button", { name: "导出历史", exact: true }).isDisabled());
  await page.getByRole("button", { name: "重置筛选", exact: true }).click();
  await page.getByLabel("网页字号").selectOption("150");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  await page.screenshot({ path: "outputs/history-mobile.png", fullPage: true });
  await page.getByLabel("演示角色").selectOption("visitor");
  assert.equal(await page.getByText("查看变更前后", { exact: true }).count(), 0);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByLabel("网页字号").selectOption("130");
  await page.screenshot({ path: "outputs/history-desktop.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: multiple change types, keyword AND execution time range, Beijing cross-midnight boundaries, one-sided search, invalid/empty results, filtered CSV export, reset and mobile large-font layout");
} finally { await browser.close(); }
