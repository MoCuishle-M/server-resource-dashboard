  const bar = purpose => page.locator(".timeline-booking").filter({ hasText: purpose });
  await bar("QA手调重点一").click();
  let d = page.getByRole("dialog", { name: "调整排期优先级", exact: true });
  assert(await d.getByRole("button", { name: "保存优先级", exact: true }).isDisabled());
  await d.getByLabel("调整后的优先级").selectOption("high");
  assert.match(await d.getByRole("region", { name: "优先级调整影响预览" }).innerText(), /QA基础低优排期.*被抢占/s);
  await d.getByLabel("调整优先级原因").fill("重点实验优先");
  assert(await d.getByRole("button", { name: "保存优先级", exact: true }).isDisabled());
  await d.getByRole("checkbox", { name: /确认调整优先级/ }).check();
  await page.screenshot({ path: "outputs/priority-adjustment/desktop-form.png", fullPage: true });
  await d.getByRole("button", { name: "保存优先级", exact: true }).click(); await d.waitFor({ state: "hidden" });
  assert.match(await bar("QA手调重点一").getAttribute("class"), /priority-high/);
  assert.match(await bar("QA手调重点二").innerText(), /暂不可用/);
  await bar("QA手调重点二").click();
  d = page.getByRole("dialog", { name: "调整排期优先级", exact: true });
  await d.getByLabel("调整后的优先级").selectOption("high");
  assert.match(await d.getByRole("region", { name: "优先级调整影响预览" }).innerText(), /同级共享.*QA手调重点一/s);
  await d.getByLabel("调整优先级原因").fill("与重点一同级共用");
  await d.getByRole("checkbox", { name: /确认调整优先级/ }).check();
  await d.getByRole("button", { name: "保存优先级", exact: true }).click(); await d.waitFor({ state: "hidden" });
  assert.match(await bar("QA手调重点一").getAttribute("title"), /同级共享 · 可用/);
  assert.match(await bar("QA手调重点二").getAttribute("title"), /同级共享 · 可用/);
  assert.equal(await bar("QA基础低优排期").locator(".timeline-blocked-overlay").count(), 1);
  await page.screenshot({ path: "outputs/priority-adjustment/two-high-timeline.png", fullPage: true });
  await bar("QA手调重点二").click();
  d = page.getByRole("dialog", { name: "调整排期优先级", exact: true });
  await d.getByLabel("调整后的优先级").selectOption("normal");
  assert.match(await d.getByRole("region", { name: "优先级调整影响预览" }).innerText(), /暂不可用/);
  await d.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByRole("button", { name: "申请与审批", exact: true }).click();
  await page.getByRole("button", { name: "全部申请", exact: true }).click();
  await page.getByRole("row").filter({ hasText: "QA手调重点一" }).getByRole("button", { name: "调整优先级", exact: true }).click();
  d = page.getByRole("dialog", { name: "调整排期优先级", exact: true });
  assert.equal(await d.getByLabel("调整后的优先级").inputValue(), "high");
  await d.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByRole("button", { name: "变更历史", exact: true }).click();
  assert.match(await page.locator("main").innerText(), /调整排期优先级/);
  await page.getByRole("button", { name: "使用排期", exact: true }).click();
  await page.getByRole("button", { name: "单日", exact: true }).click(); await page.getByLabel("排期日期").fill(date); await page.getByLabel("搜索排期资源").fill("192.0.2.11");
  await page.setViewportSize({ width: 390, height: 844 });
  await bar("QA手调重点一").click();
  d = page.getByRole("dialog", { name: "调整排期优先级", exact: true });
  await d.getByLabel("调整后的优先级").selectOption("urgent");
  await d.getByRole("region", { name: "优先级调整影响预览" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "outputs/priority-adjustment/mobile-form.png", fullPage: true });
  assert(await d.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await d.getByLabel("调整优先级原因").fill("手机端提升紧急等级");
  await d.getByRole("checkbox", { name: /确认调整优先级/ }).check();
  await d.getByRole("button", { name: "保存优先级", exact: true }).click(); await d.waitFor({ state: "hidden" });
  assert.match(await bar("QA手调重点一").getAttribute("class"), /priority-urgent/);
  assert.match(await bar("QA手调重点二").innerText(), /暂不可用/);
  await page.setViewportSize({ width: 1600, height: 1100 });
  await page.getByLabel("演示角色").selectOption("visitor");
  await bar("QA手调重点一").click();
  const details = page.getByRole("dialog");
  assert.equal(await details.getByRole("button", { name: "调整优先级", exact: true }).count(), 0);
  assert.notEqual(await details.getAttribute("aria-label"), "调整排期优先级");
  assert.deepEqual(errors, []);
  console.log("PASS priority editing: timeline/list entries, preemption preview, peer sharing, downgrade preview, audit, mobile save and visitor access");
