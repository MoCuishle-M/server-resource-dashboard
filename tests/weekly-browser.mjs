  assert.equal((await download).suggestedFilename(), `${week}周排期.csv`);
  await page.screenshot({ path: "outputs/weekly/desktop.png", fullPage: true });
  await page.getByRole("button", { name: "申请与审批", exact: true }).click();
  assert.match(await page.locator("main").innerText(), /QA周排期 · 同柜训练/);
  await page.getByRole("button", { name: "每周需求与排期", exact: true }).click();
  await page.getByRole("button", { name: "创建周计划", exact: true }).click();
  dialog = page.getByRole("dialog");
  const next = new Date(`${week}T12:00:00Z`); next.setUTCDate(next.getUTCDate() + 7);
  await dialog.getByLabel("周起始日期（北京时间周一）").fill(next.toISOString().slice(0, 10));
  await dialog.getByRole("button", { name: "创建并开始收集", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "带入上期需求", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".weekly-table")?.textContent.includes("QA周排期"));
  await page.getByLabel("演示角色").selectOption("visitor");
  assert.equal(await page.getByRole("button", { name: "创建周计划", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "提交任务需求", exact: true }).count(), 0);
  assert.equal(await page.getByLabel("选择周排期").locator("option").count(), 1, "visitor sees only published weeks");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "每周需求与排期", exact: true }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "no page-level horizontal overflow");
  await page.screenshot({ path: "outputs/weekly/mobile.png", fullPage: true });
  await page.getByLabel("演示角色").selectOption("admin");
  await page.getByRole("button", { name: "提交任务需求", exact: true }).click();
  dialog = page.getByRole("dialog");
  assert.ok(await dialog.evaluate(e => e.getBoundingClientRect().width <= innerWidth));
  await page.screenshot({ path: "outputs/weekly/mobile-form.png", fullPage: true });
  await dialog.getByRole("button", { name: "关闭", exact: true }).click();
  assert.deepEqual(errors, []);
  console.log("PASS: weekly demand, multiple resource types, same-rack suggestion, locks, contact confirmation, publication, CSV, prior-week copy, public privacy, desktop and mobile layouts");
