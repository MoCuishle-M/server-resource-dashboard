import { chromium } from "playwright";
import ExcelJS from "exceljs";
import assert from "node:assert/strict";
const base = process.env.BASE_URL ?? "http://127.0.0.1:5173";
const proxy = process.env.HTTPS_PROXY ?? process.env.https_proxy;
const browser = await chromium.launch({ headless: true, channel: "chromium", args: ["--no-sandbox"],
  ...(proxy && !/^http:\/\/(127\.0\.0\.1|localhost)/.test(base) ? { proxy: { server: proxy } } : {}),
});
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(base + "/demo", { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "服务器资源", exact: true }).click();
  await page.getByRole("button", { name: "添加服务器", exact: true }).click();
  let d = page.getByRole("dialog");
  await d.getByLabel("服务器名称").fill("QA-Lingshu-A");
  await d.getByLabel("服务器类型").fill("950DT*8卡");
  await d.getByLabel("IP 地址").fill("198.51.100.181");
  await d.getByLabel("使用方式", { exact: true }).selectOption("lingshu");
  await d.getByLabel("灵枢平台状态", { exact: true }).selectOption("ticket");
  await d.getByRole("button", { name: "保存服务器", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  await page.getByLabel("搜索资源", { exact: true }).fill("QA-Lingshu-");
  let rows = page.locator(".resource-table tbody tr");
  assert.equal(await rows.count(), 1);
  assert((await rows.innerText()).includes("通过工单占用"));
  await page.getByRole("button", { name: "编辑 QA-Lingshu-A", exact: true }).click();
  d = page.getByRole("dialog");
  await d.getByLabel("灵枢平台状态", { exact: true }).selectOption("pool_platform");
  await d.getByRole("button", { name: "保存服务器", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  assert((await rows.innerText()).includes("通过统一资源池+灵枢平台使用"));
  await page.getByLabel("全选当前结果").check();
  await page.getByRole("button", { name: "批量修改", exact: true }).click();
  d = page.getByRole("dialog");
  await d.getByLabel("修改灵枢平台状态", { exact: true }).check();
  await d.getByLabel("批量灵枢平台状态", { exact: true }).selectOption("platform");
  await d.getByRole("button", { name: "确认批量修改", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  await page.getByLabel("状态筛选").selectOption("lingshu:platform");
  assert.equal(await rows.count(), 1);
  assert((await rows.innerText()).includes("通过灵枢平台使用"));
  await page.getByLabel("状态筛选").selectOption("");
  await page.getByRole("button", { name: "批量导入", exact: true }).click();
  d = page.getByRole("dialog");
  const workbook = new ExcelJS.Workbook();
  workbook.addWorksheet("资源").addRows([
    ["名称", "类型", "IP", "使用方式", "灵枢平台状态"],
    ["QA-Lingshu-B", "950DT*8卡", "198.51.100.182", "灵枢平台", "通过工单占用"],
  ]);
  await d.getByLabel("上传资源表格").setInputFiles({ name: "灵枢资源.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from(await workbook.xlsx.writeBuffer()) });
  await d.getByText("通过工单占用", { exact: true }).waitFor();
  await d.getByRole("button", { name: "确认导入", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  assert.equal(await rows.count(), 2);
  const tomorrow = new Date(Date.now() + 86400000 + 8 * 3600000).toISOString().slice(0, 10);
  await page.getByRole("button", { name: "申请资源", exact: true }).click();
  d = page.getByRole("dialog");
  await d.getByText("QA-Lingshu-A", { exact: true }).click();
  const participant = d.getByLabel("使用者", { exact: true });
  assert.equal(await participant.locator("option").count(), 11);
  await participant.selectOption({ label: "灵枢平台" });
  await d.getByLabel("时间窗口日期").fill(tomorrow);
  await d.getByRole("button", { name: "09:00–12:00", exact: true }).click();
  await d.getByLabel("任务用途").fill("QA灵枢平台排期");
  await d.getByRole("button", { name: "提交申请", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  let request = page.getByRole("row").filter({ hasText: "QA灵枢平台排期" });
  assert((await request.innerText()).includes("灵枢平台"));
  await request.getByRole("button", { name: "审批", exact: true }).click();
  d = page.getByRole("dialog");
  await d.getByRole("button", { name: "确认批准", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "使用排期", exact: true }).click();
  await page.getByLabel("排期日期").fill(tomorrow);
  await page.getByLabel("排期组筛选").selectOption({ label: "灵枢平台" });
  const booking = page.locator(".timeline-booking").filter({ hasText: "QA灵枢平台排期" });
  assert.equal(await booking.count(), 1);
  assert((await booking.innerText()).includes("灵枢平台"));
  await page.getByRole("button", { name: "团队与接口人", exact: true }).click();
  await page.getByRole("button", { name: "编辑灵枢平台", exact: true }).click();
  d = page.getByRole("dialog");
  assert.equal(await d.locator('input[name="name"]').getAttribute("readonly"), "");
  await d.getByLabel("接口人姓名").fill("平台接口人");
  await d.getByLabel("接口人工号").fill("LING001");
  await d.getByRole("button", { name: "保存信息", exact: true }).click();
  await d.waitFor({ state: "hidden" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel("网页字号").selectOption("150");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  await page.screenshot({ path: "outputs/lingshu-groups-mobile.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: three Lingshu statuses, edit/bulk/filter/XLSX import, ten groups plus platform participant, approved platform timeline and editable platform contact");
} finally { await browser.close(); }
